package rpm

import "testing"

func TestCompareEVR(t *testing.T) {
	for _, c := range []struct {
		a, b string
		want int
	}{
		{"1.0", "1.0", 0},
		{"1.0", "2.0", -1},
		{"2.0.1", "2.0.1a", -1},
		{"5.5p1", "5.5p2", -1},
		{"5.5p10", "5.5p1", 1},
		{"10xyz", "10.1xyz", -1},
		{"xyz10", "xyz10.1", -1},
		{"xyz.4", "xyz.4", 0},
		{"xyz.4", "8", -1},
		{"xyz.4", "2", -1},
		{"5.5p2", "5.6p1", -1},
		{"5.6p1", "6.5p1", -1},
		{"6.0.rc1", "6.0", 1},
		{"10b2", "10a1", 1},
		{"10a2", "10b2", -1},
		{"1.0aa", "1.0aa", 0},
		{"1.0a", "1.0aa", -1},
		{"10.0001", "10.0039", -1},
		{"4.999.9", "5.0", -1},
		{"20101121", "20101122", -1},
		{"2_0", "2_0", 0},
		{"2.0", "2_0", 0},
		{"a+", "a_", 0},
		{"+a", "_a", 0},
		{"+_", "_+", 0},
		{"1.0~rc1", "1.0", -1},
		{"1.0~rc1", "1.0~rc2", -1},
		{"1.0~rc1~git123", "1.0~rc1", -1},
		{"1.0^", "1.0", 1},
		{"1.0^git1", "1.0", 1},
		{"1.0^git1", "1.0^git2", -1},
		{"1.0^git1", "1.01", -1},
		{"1.0^20160101", "1.0.1", -1},
		{"1.0~rc1^git1", "1.0~rc1", 1},
		{"1.0^git1~pre", "1.0^git1", -1},
		{"0.43.0-1", "0.43.1-1", -1},
		{"0.43.0-2", "0.43.0-10", -1},
		{"1:0.1-1", "2.0-1", 1},
		{"0:2.0-1", "2.0-1", 0},
	} {
		if got := CompareEVR(c.a, c.b); got != c.want {
			t.Errorf("CompareEVR(%q, %q) = %d, want %d", c.a, c.b, got, c.want)
		}
		if got := CompareEVR(c.b, c.a); got != -c.want {
			t.Errorf("CompareEVR(%q, %q) = %d, want %d", c.b, c.a, got, -c.want)
		}
	}
}
